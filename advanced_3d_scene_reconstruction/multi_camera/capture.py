#!/usr/bin/env python3
"""Threaded multi-camera capture and synchronized RGB-D sample bundling.

The manager owns adapter lifecycle and one bounded queue per camera. It
converts each sample timestamp into the selected master clock before pairing.
A bundle is emitted only when every configured camera contributes a sample
within the skew budget. No hardware trigger is generated by this module.
"""
from __future__ import annotations
from collections import deque
from dataclasses import dataclass
import threading
import time
from typing import Dict, Mapping, Optional

from camera_adapters import CameraAdapter, CameraSample
from common import CameraFrame, DepthMap
from .time_sync import ClockModel


@dataclass
class CaptureBundle:
    samples: Dict[str, CameraSample]
    timestamp: float
    max_skew_s: float


class MultiCameraCaptureManager:
    """Concurrent adapter runner with bounded queues and deterministic cleanup."""
    def __init__(self, adapters: Mapping[str, CameraAdapter],
                 clock_models: Optional[Mapping[str, ClockModel]] = None,
                 tolerance_s: float = 0.008, queue_size: int = 8,
                 read_retry_s: float = 0.002):
        if len(adapters) < 2 or len(set(adapters)) != len(adapters):
            raise ValueError("At least two uniquely named camera adapters are required")
        if tolerance_s < 0 or queue_size < 1 or read_retry_s <= 0:
            raise ValueError("Invalid capture manager limits")
        self.adapters = dict(adapters)
        self.camera_ids = tuple(adapters)
        self.clock_models = dict(clock_models or {
            c: ClockModel() for c in self.camera_ids})
        if set(self.clock_models) != set(self.camera_ids):
            raise ValueError("Provide exactly one clock model per adapter")
        self.tolerance_s = float(tolerance_s)
        self.queue_size = int(queue_size)
        self.read_retry_s = float(read_retry_s)
        self.queues = {c: deque() for c in self.camera_ids}
        self.stats = {c: {"captured": 0, "queue_overflow": 0,
                          "out_of_order": 0, "stale": 0,
                          "read_none": 0, "errors": 0} for c in self.camera_ids}
        self._last_timestamp = {c: -float("inf") for c in self.camera_ids}
        self._condition = threading.Condition()
        self._stop = threading.Event()
        self._threads = []
        self._opened = []
        self._errors = {}
        self._running = False
        self.bundles_emitted = 0
        self.bundles_rejected = 0

    def start(self):
        if self._running:
            raise RuntimeError("Capture manager is already running")
        self._stop.clear()
        try:
            for camera_id, adapter in self.adapters.items():
                adapter.open()
                self._opened.append(camera_id)
        except Exception:
            self.close()
            raise
        self._running = True
        for camera_id, adapter in self.adapters.items():
            thread = threading.Thread(
                target=self._reader_loop, args=(camera_id, adapter),
                name=f"camera-reader-{camera_id}", daemon=True)
            self._threads.append(thread)
            thread.start()
        return self

    def _normalize_sample(self, camera_id: str, sample: CameraSample):
        if sample.frame.camera_id != camera_id:
            raise ValueError(
                f"Adapter {camera_id} returned frame for {sample.frame.camera_id}")
        model = self.clock_models[camera_id]
        master_t = model.to_master(sample.frame.timestamp)
        frame = CameraFrame(
            sample.frame.image, master_t, camera_id, sample.frame.frame_id,
            sample.frame.color_order,
            metadata={**sample.frame.metadata,
                      "device_timestamp_s": sample.frame.timestamp,
                      "master_timestamp_s": master_t,
                      "clock_scale": model.scale,
                      "clock_offset_s": model.offset_s})
        depth = sample.depth
        if depth is not None:
            depth_master_t = model.to_master(depth.timestamp)
            if abs(depth_master_t - master_t) > 0.001:
                raise ValueError(f"RGB/depth timestamps disagree for {camera_id}")
            depth = DepthMap(depth.depth, master_t, camera_id,
                             valid_mask=depth.valid_mask, unit=depth.unit,
                             uncertainty=depth.uncertainty)
        return CameraSample(frame, sample.calibration, depth)

    def _reader_loop(self, camera_id, adapter):
        while not self._stop.is_set():
            try:
                sample = adapter.read()
                if sample is None:
                    self.stats[camera_id]["read_none"] += 1
                    self._stop.wait(self.read_retry_s)
                    continue
                normalized = self._normalize_sample(camera_id, sample)
                with self._condition:
                    timestamp = normalized.frame.timestamp
                    if timestamp <= self._last_timestamp[camera_id]:
                        self.stats[camera_id]["out_of_order"] += 1
                        continue
                    q = self.queues[camera_id]
                    if len(q) >= self.queue_size:
                        q.popleft()
                        self.stats[camera_id]["queue_overflow"] += 1
                    q.append(normalized)
                    self._last_timestamp[camera_id] = timestamp
                    self.stats[camera_id]["captured"] += 1
                    self._condition.notify_all()
            except Exception as exc:
                self.stats[camera_id]["errors"] += 1
                with self._condition:
                    self._errors[camera_id] = exc
                    self._condition.notify_all()
                self._stop.set()
                break

    def _try_bundle_locked(self):
        if any(not q for q in self.queues.values()):
            return None
        while all(self.queues.values()):
            heads = {c: q[0].frame.timestamp for c, q in self.queues.items()}
            latest = max(heads.values())
            for camera_id, q in self.queues.items():
                while q and latest - q[0].frame.timestamp > self.tolerance_s:
                    q.popleft()
                    self.stats[camera_id]["stale"] += 1
            if any(not q for q in self.queues.values()):
                return None
            selected = {
                c: min(q, key=lambda s: abs(s.frame.timestamp - latest))
                for c, q in self.queues.items()
            }
            stamps = [s.frame.timestamp for s in selected.values()]
            skew = max(stamps) - min(stamps)
            if skew <= self.tolerance_s:
                for camera_id, sample in selected.items():
                    q = self.queues[camera_id]
                    while q:
                        item = q.popleft()
                        if item is sample:
                            break
                self.bundles_emitted += 1
                return CaptureBundle(selected, float(sum(stamps) / len(stamps)),
                                     float(skew))
            earliest = min(selected, key=lambda c: selected[c].frame.timestamp)
            self.queues[earliest].popleft()
            self.stats[earliest]["stale"] += 1
            self.bundles_rejected += 1
        return None

    def read_bundle(self, timeout_s: float = 1.0) -> Optional[CaptureBundle]:
        if not self._running:
            raise RuntimeError("Capture manager is not running")
        if timeout_s < 0:
            raise ValueError("timeout_s must be non-negative")
        deadline = time.monotonic() + timeout_s
        with self._condition:
            while True:
                bundle = self._try_bundle_locked()
                if bundle is not None:
                    return bundle
                if self._errors:
                    camera_id, error = next(iter(self._errors.items()))
                    raise RuntimeError(f"Camera reader {camera_id} failed: {error}") from error
                if self._stop.is_set():
                    return None
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    return None
                self._condition.wait(remaining)

    def snapshot_stats(self):
        with self._condition:
            return {
                "cameras": {c: dict(v) for c, v in self.stats.items()},
                "bundles_emitted": self.bundles_emitted,
                "bundles_rejected": self.bundles_rejected,
                "errors": {c: str(e) for c, e in self._errors.items()},
                "queue_depths": {c: len(q) for c, q in self.queues.items()},
            }

    def close(self):
        self._stop.set()
        with self._condition:
            self._condition.notify_all()
        for thread in self._threads:
            thread.join(timeout=2.0)
        self._threads.clear()
        for camera_id in reversed(self._opened):
            try:
                self.adapters[camera_id].close()
            except Exception:
                pass
        self._opened.clear()
        self._running = False

    def __enter__(self):
        return self.start()

    def __exit__(self, exc_type, exc, tb):
        self.close()
